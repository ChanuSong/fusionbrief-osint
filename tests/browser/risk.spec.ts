import { test, expect } from '@playwright/test';
const id = '20000000-0000-0000-0000-000000000003';
test('risk conclusion → color graph → exact citation → action → review invalidation on mobile', async ({ page, request }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/'); await page.locator('.recent-runs button').filter({ hasText: '자동 검증 전용 가상 항만 위험 분석' }).click();
  await expect(page.locator('.risk-conclusion')).toContainText('상승');
  await expect(page.locator('.risk-conclusion')).toContainText('근거 신뢰도: 중간');
  await expect(page.locator('.risk-matrix .risk-current-cell')).toContainText('상승');
  await expect(page.locator('#report-risk .risk-scale').first()).toHaveAccessibleName(/추가 접근 거부 위험도 상승/);
  await page.locator('#report-risk .answer-citations button').first().click();
  await expect(page.getByRole('dialog').locator('mark')).toContainText('Vessel V was turned away');
  await page.keyboard.press('Escape');
  await expect(page.locator('#report-actions')).toContainText('완료 조건');
  await expect(page.locator('#report-actions')).toContainText('24시간 내');
  await expect(page.locator('.portfolio-channel')).toHaveCount(11);
  await expect(page.locator('.simulation-heading')).toContainText('모의 데이터');
  await page.getByRole('button', {name:'선박 · 모의',exact:true}).click();
  await expect(page.locator('.simulated-workspace h4')).toContainText('선박 위치');
  await expect(page.locator('.simulation-chart')).toHaveAccessibleName(/모의 위치 경로/);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#report-risk').scrollIntoViewIfNeeded();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy();
  await page.screenshot({ path: 'test-results/risk-mobile.png' });
  const stored = await (await request.get(`/api/runs/${id}`)).json();
  const changed = await request.post(`/api/runs/${id}/reviews`, { data: { expectedVersion: stored.version, claimId: 'access-claim', action: 'independence', evidenceIds: ['access-claim-e1'], independent: true, reason: '위험 평가 브라우저 검증 전용 원출처 검토' } });
  expect(changed.status()).toBe(200);
  await page.reload(); await page.locator('.history-section > summary').click();
  await page.locator('.recent-runs button').filter({ hasText: '자동 검증 전용 가상 항만 위험 분석' }).click();
  await expect(page.locator('.risk-conclusion')).toContainText('판단 유보');
  await expect(page.locator('#report-risk')).toHaveCount(0);
  await expect(page.locator('#report-actions')).toHaveCount(0);
  const md = await (await request.get(`/api/runs/${id}/export`)).text();
  expect(md).toContain('판단 유보'); expect(md).not.toContain('## 권장 추가 액션');
  expect(errors).toEqual([]);
});
