import {test,expect} from '@playwright/test';
import {openSavedScenario} from './saved-report.ts';
test('primary succession brief → criteria → visual original → scenarios → approval → changed-source hold',async({page,request})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  const run=await openSavedScenario(page,request,'nk-succession');
  expect(run.demo!.scenarioId).toBe('nk-succession');
  await expect(page.locator('.report-document h1')).toHaveText(run.question);
  await expect(page.locator('.document-metadata')).toContainText('검토 전 초안');
  await expect(page.locator('.framework-lead')).toContainText('김주애');
  await expect(page.locator('.intel-report-meta')).toContainText('ICD 203');
  await expect(page.locator('.intel-key-judgments li')).toHaveCount(2);
  await expect(page.locator('.intel-indicator-comparison tbody tr')).toHaveCount(6);
  await expect(page.locator('.criterion-details')).not.toHaveAttribute('open','');
  await expect(page.locator('.intel-outlook article')).toHaveCount(3);
  await expect(page.getByRole('heading',{name:'정보 공백과 후속 수집'})).toBeVisible();
  await expect(page.getByRole('tab',{name:'지도',exact:true})).toHaveCount(0);
  await expect(page.locator('#report-imagery img')).toHaveCount(1);
  await page.locator('#report-imagery img').scrollIntoViewIfNeeded();
  await expect.poll(()=>page.locator('#report-imagery img').evaluate((image:HTMLImageElement)=>image.complete && image.naturalWidth>0)).toBeTruthy();
  const asset=await request.get(`/api/media/${run.imagery![0].mediaHash}`);expect(asset.status()).toBe(200);expect(asset.headers()['content-type']).toMatch(/^image\//);
  await page.locator('.criterion-details > summary').click();
  await page.getByRole('button',{name:'공식 지명·직책 부여 기준 원문 보기'}).first().click();
  await expect(page.getByRole('dialog').locator('mark')).toContainText('혈통승계 절차');
  await page.keyboard.press('Escape');
  await page.locator('.framework-lead .answer-citations button').first().click();
  await expect(page.getByRole('dialog').locator('mark')).toBeVisible();await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'주석 1 원문 보기',exact:true}).click();
  await expect(page.getByRole('dialog').locator('mark')).toHaveText(run.evidence[0].quote);
  await page.keyboard.press('Escape');
  await page.emulateMedia({media:'print'});
  await expect(page.locator('.report-tools')).toBeHidden();
  await expect(page.locator('.topbar')).toBeHidden();
  await expect(page.locator('#report-sources')).toBeVisible();
  await page.pdf({path:'test-results/nk-intel-print.pdf',preferCSSPageSize:true,printBackground:true});
  // Printing exposes material limitations and restores the reader's disclosure state.
  await page.emulateMedia({media:'screen'});
  await expect(page.locator('.document-judgment-limits details')).not.toHaveAttribute('open','');
  const graph=await(await request.get(`/api/runs/${run.id}/ontology`)).json();
  expect(graph['@graph'].filter((n:{'@type':string})=>n['@type']==='Forecast')).toHaveLength(3);
  expect(graph['@graph'].filter((n:{'@type':string})=>n['@type']==='VisualObservation')).toHaveLength(1);
  await page.screenshot({path:'test-results/nk-intel-desktop.png',fullPage:true});
  await page.getByText('검토 결정 기록',{exact:true}).click();
  await page.getByLabel('검토자',{exact:true}).fill('브라우저 검증 분석가');
  await page.getByLabel('검토 의견').fill('검증 전용: 공식 지명 미확인과 조건부 전망의 한계를 포함한 초안 승인 흐름 확인');
  await page.getByRole('button',{name:'결정 저장'}).click();await expect(page.locator('.approval-record')).toContainText('브라우저 검증 분석가');
  await expect(page.locator('.document-metadata')).toContainText('분석가 승인');
  const markdown=await(await request.get(`/api/runs/${run.id}/export`)).text();
  expect(markdown).toContain('## 주요 판단');expect(markdown).toContain('## 전망과 변화 징후');expect(markdown).toContain('원본 SHA-256');
  const approved=await(await request.get(`/api/runs/${run.id}`)).json();
  const claim=approved.claims.find((c:{id:string})=>approved.analysis.judgment.claimIds.includes(c.id));
  const review=await request.post(`/api/runs/${run.id}/reviews`,{data:{expectedVersion:approved.version,claimId:claim.id,action:'independence',evidenceIds:[claim.evidenceIds[0]],independent:false,reason:'검증 전용: 독립성 확인 보류에 따른 전망 재검증 조건 확인'}});
  expect(review.status()).toBe(200);const pending=await review.json();expect(pending.analysis.verification).toBe('pending');expect(pending.approval).toBeUndefined();
  const held=await(await request.get(`/api/runs/${run.id}/export`)).text();expect(held).not.toContain('## 전망과 변화 징후');expect(held).toContain('재검증이 필요합니다');
  await page.setViewportSize({width:390,height:844});await page.locator('.framework-conclusion').scrollIntoViewIfNeeded();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
  await page.screenshot({path:'test-results/nk-intel-mobile.png',fullPage:false});expect(errors).toEqual([]);
});
