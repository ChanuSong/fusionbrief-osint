import { test, expect } from '@playwright/test';
import { readFile } from 'node:fs/promises';
import { openSavedScenario } from './saved-report.ts';

test('archived APAC report → multilingual quotes → reasoning → map → source merge → approval → export', async ({ page, request }) => {
  test.setTimeout(60000);
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  const started = Date.now();
  const loadStart = Date.now();
  const run = await openSavedScenario(page, request, 'taiwan-strait-2026');
  await expect(page.locator('.answer-list.composed-answer')).toContainText('봉쇄');
  const loadMs = Date.now() - loadStart;
  expect(loadMs).toBeLessThan(5000);
  await expect(page.locator('.demo-provenance')).toContainText('사전 수집·검증 결과');
  await page.screenshot({ path: 'test-results/demo-answer.png', fullPage: false });
  await page.locator('.relation-insights > summary').click();
  await expect(page.locator('.relation-insights')).toHaveAttribute('open', '');
  for (const [label, code] of [['한국어','KO'],['중국어','ZH'],['일본어','JA'],['러시아어','RU']]) {
    await page.getByRole('group', { name: '원문 언어 필터' }).getByRole('button', { name: new RegExp(label) }).click();
    await page.getByRole('button', { name: new RegExp(`^${code} 인용`) }).first().click();
    await expect(page.getByRole('dialog').locator('mark')).toBeVisible();
    await page.keyboard.press('Escape');
  }
  await page.screenshot({ path: 'test-results/demo-language.png' });
  await expect(page.getByRole('heading', { name: '판단을 뒷받침하는 정보' })).toBeVisible();
  await expect(page.locator('.cytoscape-viewport canvas').first()).toBeVisible();
  await expect(page.locator('.relation-insights')).toHaveAttribute('open', '');
  await page.getByRole('button', { name: '이 해석의 근거 관계 보기' }).click();
  await expect(page.locator('.relation-insights')).toContainText('다른 설명');
  await page.screenshot({ path: 'test-results/demo-graph.png' });
  await page.getByRole('button', { name: '공군 11월 훈련 공고 판단 선택', exact: true }).click();
  await page.getByRole('tab', { name: '타임라인', exact: true }).click();
  await expect(page.locator('#panel-timeline')).toContainText('공군 훈련 첫 예정일');
  await page.getByRole('tab', { name: '지도', exact: true }).click();
  await expect(page.locator('.leaflet-overlay-pane path')).not.toHaveCount(0);
  await page.getByRole('button', { name: /^좌표 원문 확인/ }).click();
  await expect(page.getByRole('dialog').locator('mark')).toContainText('22°38');
  await page.keyboard.press('Escape');
  await page.screenshot({ path: 'test-results/demo-map.png' });
  await page.getByRole('button', { name: '10월 10일 국방부 일일 동태 판단 선택' }).click();
  await page.getByRole('tab', { name: '원출처', exact: true }).click();
  await expect(page.locator('.funnel-step').nth(1)).toContainText('2');
  await page.getByRole('button', { name: '분석가 검토', exact: true }).click();
  await page.getByRole('checkbox', { name: 'mnd.gov.tw 근거 선택', exact: true }).check();
  await page.getByRole('checkbox', { name: 'newtalk.tw 근거 선택', exact: true }).first().check();
  await page.getByLabel('검토 이유').fill('Newtalk 기사와 국방부 발표의 집계 기간·수치·귀속 문구를 대조했습니다. 같은 10월 10일 발표의 재인용으로 묶고, 독립성은 미확인으로 유지합니다.');
  await page.getByRole('button', { name: '검토 반영', exact: true }).click();
  await expect(page.locator('.report-header')).toContainText('v2');
  await expect(page.locator('.funnel-step').nth(1)).toContainText('1');
  await expect(page.locator('.answer-list.composed-answer')).toContainText('봉쇄');
  await page.getByText('검토 결정 기록', { exact: true }).click();
  await page.getByLabel('검토자', { exact: true }).fill('시연 분석가');
  await page.getByLabel('검토 의견').fill('당사자 발표와 재인용 관계를 확인했습니다. 봉쇄 개시 여부는 확인 불가하며, 중국 측 원문과 현장 관측의 추가 확보가 필요하다는 한계를 포함해 승인합니다.');
  await page.getByRole('button', { name: '결정 저장' }).click();
  await expect(page.locator('.approval-record')).toContainText('시연 분석가');
  const downloaded = page.waitForEvent('download');
  await page.getByRole('link', { name: 'Markdown 내려받기' }).click();
  const markdown = await readFile((await (await downloaded).path())!, 'utf8');
  expect(markdown).toContain('시연 분석가'); expect(markdown).toContain('새 검색을 수행하지 않았습니다');
  const saved = await (await request.get(`/api/runs/${run.id}`)).json();
  expect(saved.version).toBe(3); expect(saved.approval.decision).toBe('approved');
  const fresh = await (await request.post('/api/demo/start', { data: { scenarioId: 'taiwan-strait-2026' } })).json();
  expect(fresh.version).toBe(1); expect(fresh.approval).toBeUndefined(); expect(fresh.claims.find((c: {id:string}) => c.id === 'c-mnd-1010').groups).toHaveLength(2);
  await page.getByRole('button', { name: '새 분석', exact: true }).click();
  await openSavedScenario(page, request, 'nk-pow-disclosure');
  await expect(page.locator('.answer-list.composed-answer')).toContainText('우크라이나');
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  expect(errors).toEqual([]);
  console.log(`DEMO_MEASURE load=${loadMs}ms fullFlow=${Date.now()-started}ms`);
});
